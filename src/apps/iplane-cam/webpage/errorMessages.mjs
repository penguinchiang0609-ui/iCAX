export function userErrorMessage(error) {
  const text = String(error?.message ?? error ?? "");
  const code = text.match(/PLANE_[A-Z0-9_]+/)?.[0];
  if (code && messages[code]) return messages[code];
  if (/resource.?limit|limit.?exceed/i.test(text)) return "本次输入超过当前计算限制，请查看日志中的具体限制。";
  if (/cancelled|canceled/i.test(text)) return "本次操作已取消。";
  if (/timeout|timed out/i.test(text)) return "等待操作结果超时，请查看日志后重试。";
  if (/[㐀-鿿]/.test(text) && !code) return text;
  return "操作未完成，具体原因已记录到日志。";
}

import assert from 'node:assert/strict';
import {snapTranslation,snapRotation} from '../../iCAX-UI/SDK/Viewport/transformSnapping.mjs';
const x=[1,0,0],y=[0,1,0],project=p=>p.slice(0,2),near=(a,b)=>a.forEach((v,i)=>assert.ok(Math.abs(v-b[i])<1e-8,`${a} != ${b}`));
const snap=(point,basis=[x],extra={})=>snapTranslation({point,basis,spacing:50,project,...extra});
near(snap([49,13,7]).point,[50,13,7]);
near(snap([3,0,0]).point,[0,0,0]);assert.equal(snap([3,0,0]).kind,'origin');
near(snap([2,10,0]).point,[0,10,0]);assert.equal(snap([2,10,0]).kind,'grid');
near(snap([49,51,9],[x,y]).point,[50,50,9]);
const diagonal=[Math.SQRT1_2,Math.SQRT1_2,0],tilted=snap([49,49,0],[diagonal]);
near(tilted.point,[50,50,0]);assert.ok(Math.abs(tilted.correction[0]-tilted.correction[1])<1e-8);
assert.equal(snap([25,24,9]),null);
assert.equal(snap([49,13,7],[x],{gridEnabled:false}),null);
assert.equal(snap([3,0,0],[x],{gridEnabled:false}).kind,'origin');
assert.equal(snap([25,2,3],[x],{project:p=>[p[0]*.001,p[1]],maxDistance:5}),null);
near(snap([-26,8,0],[x],{origin:[-75,-75,0]}).point,[-25,8,0]);
assert.equal(snapRotation(89*Math.PI/180),Math.PI/2);
assert.equal(snapRotation(-179*Math.PI/180),-Math.PI);
assert.equal(snapRotation(37*Math.PI/180),null);
console.log('Transform snapping: grid spacing and origin, constrained axes/planes, local direction, screen threshold, foreshortening, grid phase, and signed angle snapping passed');

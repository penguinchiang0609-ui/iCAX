import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import assert from 'node:assert/strict';
import crypto from 'node:crypto';
import {spawnSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';
import {publishArtifacts,stagePlan} from './tube_stage_outputs.mjs';

const root=fs.mkdtempSync(path.join(os.tmpdir(),'icax-tube-outputs-'));
const put=(name,text)=>{const p=path.join(root,name);fs.mkdirSync(path.dirname(p),{recursive:true});fs.writeFileSync(p,text);};
try{
  assert.deepEqual(stagePlan().stageKeys,['heal','align','contour','classify','edgeAnalysis']);
  assert.equal(stagePlan().nativeMode,'--part');
  assert.equal(stagePlan('edge-analysis',true).nativeMode,'--part-merge');
  assert.deepEqual(stagePlan('classify').publishFolders,['Heal','Align','Coutour','Classify']);
  assert.equal(stagePlan('classify').nativeMode,'--classify-only');
  assert.equal(stagePlan('classify',true).nativeMode,'--classify-merge-only');
  assert.equal(stagePlan('align',true).nativeMode,'--align-merge-only');
  assert.equal(stagePlan('contour').nativeMode,'--contour-only');
  assert.throws(()=>stagePlan('unknown'),/--until must be/);
  put('Heal/tube.STEP/part-1.step','healed');
  put('Heal/tube.STEP/part-1.json','{"status":"passed"}');
  put('Align/tube.STEP/part-1.step','aligned');
  put('Coutour/tube.STEP/part-1.step','contour');
  put('Coutour/tube.STEP/part-1.json','{}');
  put('Coutour/tube.STEP/part-1.svg','<svg/>');
  put('Coutour/tube.STEP/part-1.raw.svg','<svg>raw</svg>');
  put('Classify/tube.STEP/part-1-machining.step','machining');
  put('Classify/tube.STEP/part-1-non-machining.step','stock');
  put('EdgeAnalysis/tube.STEP/part-1.step','edge colors');
  put('EdgeAnalysis/tube.STEP/part-1.json','{"edges":[]}');
  put('EdgeAnalysis/tube.STEP/part-1.brep','whole machining BREP');
  put('EdgeAnalysis/tube.STEP/part-1.html','<html>edge styles</html>');
  const first=publishArtifacts(root,root,'tube.STEP','part-1',['tube.STEP']);
  assert.equal(fs.readFileSync(first.heal,'utf8'),'healed');
  assert.equal(JSON.parse(fs.readFileSync(first.healData,'utf8')).status,'passed');
  assert.equal(fs.readFileSync(first.align,'utf8'),'aligned');
  assert.deepEqual(Object.entries(first).filter(([,file])=>file.endsWith('.brep')).map(([key])=>key),['edgeAnalysisBrep']);
  assert.equal(fs.readFileSync(first.edgeAnalysis,'utf8'),'edge colors');
  assert.deepEqual(JSON.parse(fs.readFileSync(first.edgeAnalysisData,'utf8')),{edges:[]});
  assert.equal(fs.readFileSync(first.edgeAnalysisBrep,'utf8'),'whole machining BREP');
  assert.equal(fs.readFileSync(first.edgeAnalysisView,'utf8'),'<html>edge styles</html>');
  assert.equal(fs.readFileSync(first.contourSvg,'utf8'),'<svg/>');
  assert.equal(path.basename(first.rawProjectionSvg),'tube.raw.svg');
  assert.equal(fs.readFileSync(first.rawProjectionSvg,'utf8'),'<svg>raw</svg>');
  assert.equal(fs.readFileSync(first.nonMachining,'utf8'),'stock');
  for(const folder of ['Heal','Align','Coutour','Classify','EdgeAnalysis'])
    assert.ok(fs.readdirSync(path.join(root,folder),{withFileTypes:true}).every(e=>e.isFile()));
  const staging=path.join(root,'Reports/staging');
  put('Reports/staging/Align/tube.STEP/part-1.step','aligned again');
  const second=publishArtifacts(root,staging,'tube.STEP','part-1',['tube.STEP']);
  assert.deepEqual(Object.keys(second),['align']);
  assert.ok(!fs.existsSync(first.contour));
  for(const file of [first.heal,first.healData])assert.ok(!fs.existsSync(file));
  assert.ok(!fs.existsSync(first.contourSvg));
  assert.ok(!fs.existsSync(first.rawProjectionSvg));
  assert.equal(fs.readFileSync(path.join(root,'Reports/previous-artifacts/Coutour/tube.step'),'utf8'),'contour');
  for(const key of ['edgeAnalysis','edgeAnalysisData','edgeAnalysisBrep','edgeAnalysisView'])assert.ok(!fs.existsSync(first[key]));
  assert.equal(fs.readFileSync(path.join(root,'Reports/previous-artifacts/EdgeAnalysis/tube.brep'),'utf8'),'whole machining BREP');
  put('Reports/staging/Align/tube.IGS/part-1.step','iges');
  const distinct=publishArtifacts(root,staging,'tube.IGS','part-1',['tube.STEP','tube.IGS']);
  assert.equal(path.basename(distinct.align),'tube__igs.step');
  put('Coutour/tube.step','prior contour');
  put('Classify/tube.step','prior machining');
  for(const suffix of ['step','json','brep','html'])put(`EdgeAnalysis/tube.${suffix}`,`prior edge ${suffix}`);
  put('Reports/staging/Align/tube.STEP/part-1.step','align-only result');
  const alignOnly=publishArtifacts(root,staging,'tube.STEP','part-1',['tube.STEP'],['Heal','Align']);
  assert.deepEqual(Object.keys(alignOnly),['align']);
  assert.equal(fs.readFileSync(path.join(root,'Coutour/tube.step'),'utf8'),'prior contour');
  assert.equal(fs.readFileSync(path.join(root,'Classify/tube.step'),'utf8'),'prior machining');
  put('Reports/staging/Coutour/tube.STEP/part-1.step','contour-only result');
  const contourOnly=publishArtifacts(root,staging,'tube.STEP','part-1',['tube.STEP'],['Heal','Align','Coutour']);
  assert.equal(fs.readFileSync(contourOnly.contour,'utf8'),'contour-only result');
  assert.equal(fs.readFileSync(path.join(root,'Classify/tube.step'),'utf8'),'prior machining');
  put('Reports/staging/Classify/tube.STEP/part-1-machining.step','classify-only result');
  const classifyOnly=publishArtifacts(root,staging,'tube.STEP','part-1',['tube.STEP'],stagePlan('classify').publishFolders);
  assert.equal(fs.readFileSync(classifyOnly.machining,'utf8'),'classify-only result');
  assert.ok(!Object.hasOwn(classifyOnly,'edgeAnalysis'));
  for(const suffix of ['step','json','brep','html'])assert.equal(fs.readFileSync(path.join(root,`EdgeAnalysis/tube.${suffix}`),'utf8'),`prior edge ${suffix}`);
  for(const suffix of ['step','json','brep','html'])put(`Reports/staging/EdgeAnalysis/tube.STEP/part-1.${suffix}`,`updated edge ${suffix}`);
  const edgeOnly=publishArtifacts(root,staging,'tube.STEP','part-1',['tube.STEP'],['EdgeAnalysis']);
  assert.equal(fs.readFileSync(edgeOnly.edgeAnalysisBrep,'utf8'),'updated edge brep');
  assert.equal(fs.readFileSync(path.join(root,'Classify/tube.step'),'utf8'),'classify-only result');
  assert.deepEqual(Object.keys(edgeOnly),['edgeAnalysis','edgeAnalysisData','edgeAnalysisBrep','edgeAnalysisView']);
  const auditRoot=path.join(root,'audit-root'),auditPublish=path.join(root,'audit-publish');
  const source=path.join(root,'audit-source.step'),reportPath=path.join(auditRoot,'Reports/part.json');
  put('audit-source.step','source geometry');
  for(const folder of stagePlan().publishFolders)put(`audit-publish/${folder}/model.step`,'ISO-10303-21;\nEND-ISO-10303-21;');
  put('audit-publish/EdgeAnalysis/model.json','{}');
  put('audit-publish/EdgeAnalysis/model.brep','whole machining BREP');
  const auditSummary={status:'completed',until:'edge-analysis',publishRoot:auditPublish,sourceCount:1,
    sources:[{source,group:'model.step',status:'passed',sha256:crypto.createHash('sha256').update(fs.readFileSync(source)).digest('hex')}],
    parts:[{group:'model.step',status:'passed',reportPath,
      stages:Object.fromEntries(stagePlan().stageKeys.map(key=>[key,{status:'passed'}])),
      artifacts:{edgeAnalysis:path.join(auditPublish,'EdgeAnalysis/model.step'),edgeAnalysisData:path.join(auditPublish,'EdgeAnalysis/model.json'),edgeAnalysisBrep:path.join(auditPublish,'EdgeAnalysis/model.brep')}}]};
  const auditFile=path.join(auditRoot,'Reports/summary.json');
  const saveAudit=()=>{fs.mkdirSync(path.dirname(auditFile),{recursive:true});fs.writeFileSync(auditFile,JSON.stringify(auditSummary));};
  const runAudit=()=>spawnSync(process.execPath,[fileURLToPath(new URL('./audit_tube_stages.mjs',import.meta.url)),auditRoot],{encoding:'utf8',windowsHide:true});
  saveAudit();
  const fullAudit=runAudit();assert.equal(fullAudit.status,0,fullAudit.stderr||fullAudit.stdout);
  const auditedSummary=JSON.parse(fs.readFileSync(auditFile,'utf8'));
  assert.deepEqual(auditedSummary.counts.edgeAnalysis,{passed:1});
  assert.ok(JSON.parse(fs.readFileSync(path.join(auditRoot,'Reports/artifact-audit.json'),'utf8')).folders.EdgeAnalysis);
  delete auditSummary.parts[0].artifacts.edgeAnalysisBrep;saveAudit();
  assert.equal(runAudit().status,1,'A passed edge-analysis stage must publish its whole-model BREP.');
  const missingAudit=JSON.parse(fs.readFileSync(path.join(auditRoot,'Reports/artifact-audit.json'),'utf8'));
  assert.ok(missingAudit.missingArtifacts.some(item=>item.kind==='edgeAnalysisBrep'));
  auditSummary.until='classify';delete auditSummary.parts[0].stages.edgeAnalysis;auditSummary.parts[0].artifacts={};saveAudit();
  const classifyAudit=runAudit();assert.equal(classifyAudit.status,0,classifyAudit.stderr||classifyAudit.stdout);
  assert.ok(!Object.hasOwn(JSON.parse(fs.readFileSync(auditFile,'utf8')).counts,'edgeAnalysis'));
  assert.ok(!Object.hasOwn(JSON.parse(fs.readFileSync(path.join(auditRoot,'Reports/artifact-audit.json'),'utf8')).folders,'EdgeAnalysis'));
  console.log('TubeStageOutputsTest: passed (stage modes, whole-model BREP, flat names, failed rerun, duplicate stems, selected stages)');
}finally{
  // Delete only this test's resolved, freshly-created directory under OS temp.
  const target=fs.realpathSync(root),parent=fs.realpathSync(os.tmpdir());
  if(path.dirname(target)!==parent||!path.basename(target).startsWith('icax-tube-outputs-'))throw Error('Unexpected cleanup target');
  fs.rmSync(target,{recursive:true});
}
